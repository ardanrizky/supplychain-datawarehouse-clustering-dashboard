DROP DATABASE IF EXISTS erp_supply_chain_dm;
CREATE DATABASE erp_supply_chain_dm;
USE erp_supply_chain_dm;

CREATE TABLE dimensi_waktu (
    id_waktu INT PRIMARY KEY,
    tanggal DATE NOT NULL,
    hari VARCHAR(20) NOT NULL,
    bulan VARCHAR(20) NOT NULL,
    kuartal TINYINT NOT NULL,
    tahun YEAR NOT NULL
) ENGINE=InnoDB;

CREATE TABLE dimensi_produk (
    id_produk INT PRIMARY KEY,
    nama_produk VARCHAR(100) NOT NULL,
    kategori VARCHAR(50) NOT NULL,
    sub_kategori VARCHAR(50) NOT NULL,
    merek VARCHAR(50) NOT NULL,
    unit_satuan VARCHAR(20) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE dimensi_pemasok (
    id_pemasok INT PRIMARY KEY,
    nama_pemasok VARCHAR(100) NOT NULL,
    jenis_pemasok VARCHAR(50) NOT NULL,
    kontak_utama VARCHAR(100) NOT NULL,
    alamat_pemasok VARCHAR(150) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE dimensi_lokasi (
    id_lokasi INT PRIMARY KEY,
    nama_lokasi VARCHAR(100) NOT NULL,
    jenis_lokasi VARCHAR(20) NOT NULL,
    kota VARCHAR(50) NOT NULL,
    provinsi VARCHAR(50) NOT NULL,
    negara VARCHAR(50) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE dimensi_karyawan (
    id_karyawan INT PRIMARY KEY,
    nama_karyawan VARCHAR(100) NOT NULL,
    peran VARCHAR(50) NOT NULL,
    departemen VARCHAR(50) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE fakta_pergerakan_rantai_pasok (
    id_pergerakan INT PRIMARY KEY,
    id_waktu INT NOT NULL,
    id_produk INT NOT NULL,
    id_pemasok INT NOT NULL,
    id_lokasi INT NOT NULL,
    id_karyawan INT NOT NULL,
    jumlah_unit INT NOT NULL,
    biaya_pengiriman DECIMAL(12,2) NOT NULL,
    waktu_siklus_hari INT NOT NULL,
    nilai_inventaris DECIMAL(14,2) NOT NULL,
    jumlah_cacat INT NOT NULL,
    CONSTRAINT fk_fakta_waktu FOREIGN KEY (id_waktu) REFERENCES dimensi_waktu(id_waktu),
    CONSTRAINT fk_fakta_produk FOREIGN KEY (id_produk) REFERENCES dimensi_produk(id_produk),
    CONSTRAINT fk_fakta_pemasok FOREIGN KEY (id_pemasok) REFERENCES dimensi_pemasok(id_pemasok),
    CONSTRAINT fk_fakta_lokasi FOREIGN KEY (id_lokasi) REFERENCES dimensi_lokasi(id_lokasi),
    CONSTRAINT fk_fakta_karyawan FOREIGN KEY (id_karyawan) REFERENCES dimensi_karyawan(id_karyawan)
) ENGINE=InnoDB;

