-- Query OLAP sederhana

-- 1. Total jumlah unit per produk per bulan
SELECT
    p.nama_produk,
    w.tahun,
    w.bulan,
    SUM(f.jumlah_unit) AS total_jumlah_unit
FROM fakta_pergerakan_rantai_pasok f
JOIN dimensi_produk p ON f.id_produk = p.id_produk
JOIN dimensi_waktu w ON f.id_waktu = w.id_waktu
GROUP BY p.nama_produk, w.tahun, w.bulan
ORDER BY p.nama_produk, w.tahun,
FIELD(w.bulan, 'Januari', 'Februari', 'Maret', 'April', 'Mei', 'Juni',
               'Juli', 'Agustus', 'September', 'Oktober', 'November', 'Desember');

-- 2. Rata-rata waktu siklus pengiriman
SELECT AVG(waktu_siklus_hari) AS rata_rata_waktu_siklus_hari
FROM fakta_pergerakan_rantai_pasok;

-- 3. Total biaya pengiriman per lokasi
SELECT
    l.nama_lokasi,
    l.kota,
    SUM(f.biaya_pengiriman) AS total_biaya_pengiriman
FROM fakta_pergerakan_rantai_pasok f
JOIN dimensi_lokasi l ON f.id_lokasi = l.id_lokasi
GROUP BY l.nama_lokasi, l.kota
ORDER BY total_biaya_pengiriman DESC;

-- 4. Jumlah cacat per pemasok
SELECT
    s.nama_pemasok,
    SUM(f.jumlah_cacat) AS total_jumlah_cacat
FROM fakta_pergerakan_rantai_pasok f
JOIN dimensi_pemasok s ON f.id_pemasok = s.id_pemasok
GROUP BY s.nama_pemasok
ORDER BY total_jumlah_cacat DESC;

-- 5. Nilai inventaris per kategori produk
SELECT
    p.kategori,
    SUM(f.nilai_inventaris) AS total_nilai_inventaris
FROM fakta_pergerakan_rantai_pasok f
JOIN dimensi_produk p ON f.id_produk = p.id_produk
GROUP BY p.kategori
ORDER BY total_nilai_inventaris DESC;
